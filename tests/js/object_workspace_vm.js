'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const adapter = require('../../src/sat_sim/web/object-workspace.js');
const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const original = JSON.stringify(data);
const wheel = adapter.simulationPanelModel(data.tree, 'component.reaction_wheel');
assert.equal(wheel.ownerObjectId, 'component.reaction_wheel');
assert.ok(wheel.parameters.some(row => row.label.includes('转动惯量')));
assert.ok(wheel.outputs.some(row => row.label === '反作用轮1 · 角速度'));
assert.equal(wheel.evaluationMetrics, undefined);
assert.equal(wheel.outputs.some(row => row.kind === 'summary'), false);
assert.equal(adapter.simulationPanelModel(data.tree, 'component.link_budget').objectKind, 'relationship_object');
assert.equal(adapter.simulationPanelModel(data.tree, 'whole_spacecraft').ownerObjectId, 'whole_spacecraft');
assert.throws(() => adapter.simulationPanelModel({...data.tree, schema_version: 'workbench-object-tree.v1'}, 'whole_spacecraft'));
assert.throws(() => adapter.simulationPanelModel(data.tree, 'missing'));
const assessment = adapter.evaluationPanelModel(data.report, 'run-1');
assert.equal(assessment.title, '效能评估');
assert.equal(assessment.metrics[0].value, 2);
assert.equal(assessment.metrics[0].verdictText, '超出设定范围');
assert.equal(assessment.runStatus, undefined); // never replace a simulation status
assert.throws(() => adapter.evaluationPanelModel(data.report, 'another-run'));
assert.equal(JSON.stringify(data), original);
const unavailable = JSON.parse(JSON.stringify(data.report));
unavailable.metrics[0].status = 'NOT_EVALUATED';
unavailable.metrics[0].value = null;
unavailable.metrics[0].verdict = 'NOT_EVALUATED';
unavailable.metrics[0].reason_code = 'SOURCE_NOT_RECORDED';
const unavailableView = adapter.evaluationPanelModel(unavailable, 'run-1');
assert.equal(unavailableView.metrics[0].value, null);
assert.equal(unavailableView.metrics[0].statusText, '未评估');
assert.equal(unavailableView.metrics[0].reasonText, '本次运行未记录所需参量。');
console.log('Object workspace/evaluation contract checks passed');
